export function getEventBySlug(slug) {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim().replace(/\/+$/, "");
  return EVENTS_DATA.find(
    (e) => e.slug.toLowerCase() === normalized || e.id.toLowerCase() === normalized
  ) || EVENTS_DATA[0];
}
